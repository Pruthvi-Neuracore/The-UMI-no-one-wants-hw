"""URDFs (frames only, no meshes):

  scissor_umi_<gripper>.urdf        the handheld: base = gripper frame G, the jaw joint q (same as the robot gripper's
                                    finger_joint, mimicked on both jaws), pads, the D405 optical frame and the Quest
                                    ring frame
  <gripper>_camera.urdf.xacro       the same D405 frame as a fixed joint on robotiq_arg2f_base_link, for the
                                    robot's own Robotiq URDF (and the camera plate's 7 mm offset of the gripper from the flange)

Units: metres. G is robotiq_arg2f_base_link, so the camera and the controller have the same parent transform on both.
"""
import math

import numpy as np

import kin
import scissor as S

OUT = S.HERE.parent / kin.GRIPPER / "urdf"


def rpy(R):
    """Fixed-axis roll-pitch-yaw of a rotation matrix (URDF convention)."""
    sy = -R[2, 0]
    p = math.asin(max(-1.0, min(1.0, sy)))
    if abs(math.cos(p)) > 1e-9:
        r = math.atan2(R[2, 1], R[2, 2])
        y = math.atan2(R[1, 0], R[0, 0])
    else:
        r, y = math.atan2(-R[1, 2], R[1, 1]), 0.0
    return r, p, y


def origin(T):
    x, y, z = (T[:3, 3] / 1000.0)
    r, p, yw = rpy(T[:3, :3])
    return f'<origin xyz="{x:.5f} {y:.5f} {z:.5f}" rpy="{r:.5f} {p:.5f} {yw:.5f}"/>'


def quest_ring_frame():
    """The Quest collar's centre on the handle axis (x up the handle, z forward)."""
    import quest
    return quest.collar_frame()


def frames_xml(parent, prefix="", quest=True):
    cam, ring = S.camera_pose(), quest_ring_frame()
    q = "" if not quest else f"""
  <link name="{prefix}quest_ring_frame"/>
  <joint name="{prefix}quest_ring_joint" type="fixed">
    <parent link="{parent}"/><child link="{prefix}quest_ring_frame"/>
    {origin(ring)}
  </joint>"""
    return f"""
  <link name="{prefix}d405_optical_frame"/>
  <joint name="{prefix}d405_optical_joint" type="fixed">
    <parent link="{parent}"/><child link="{prefix}d405_optical_frame"/>
    {origin(cam)}
  </joint>{q}"""


def handheld():
    g = kin.g()
    j0 = kin.joints(0.0)
    a0 = kin.link_angle(0.0)
    af = a0 + g["finger_angle"]
    jaw = []
    for side, s, mult in (("left", 1, 1), ("right", -1, 1)):
        P1 = j0["P1"] * [s, 1]
        o1 = np.array(g["outer_to_finger"][0]) + np.array(g["outer_to_finger"][1])
        yaw = 0.0 if side == "left" else math.pi
        mimic = "" if side == "left" else '<mimic joint="finger_joint" multiplier="1"/>'
        name = "finger_joint" if side == "left" else "right_outer_knuckle_joint"
        pad = np.array(g["pad_offset"])
        jaw.append(f"""
  <link name="{side}_outer_link"/>
  <joint name="{name}" type="revolute">
    <parent link="base_link"/><child link="{side}_outer_link"/>
    <origin xyz="0 {P1[0] / 1000:.5f} {P1[1] / 1000:.5f}" rpy="{a0:.5f} 0 {yaw:.5f}"/>
    <axis xyz="-1 0 0"/><limit lower="0" upper="{g['q_max']}" effort="20" velocity="2"/>{mimic}
  </joint>
  <link name="{side}_finger"/>
  <joint name="{side}_finger_joint" type="revolute">
    <parent link="{side}_outer_link"/><child link="{side}_finger"/>
    <origin xyz="0 {o1[0] / 1000:.5f} {o1[1] / 1000:.5f}" rpy="{g['finger_angle']:.5f} 0 0"/>
    <axis xyz="1 0 0"/><limit lower="0" upper="{g['q_max']}" effort="20" velocity="2"/>
    <mimic joint="finger_joint" multiplier="1"/>
  </joint>
  <link name="{side}_pad"/>
  <joint name="{side}_pad_joint" type="fixed">
    <parent link="{side}_finger"/><child link="{side}_pad"/>
    <origin xyz="0 {pad[0] / 1000:.5f} {pad[1] / 1000:.5f}" rpy="0 0 0"/>
  </joint>""")
    return f"""<?xml version="1.0"?>
<!-- Scissor-UMI ({kin.GRIPPER}) handheld. Generated by scissor-umi/cad/urdf.py. base_link = the gripper frame G =
     the robot's robotiq_arg2f_base_link: the jaws, the D405 and the Quest ring sit at the same transforms on both.
     q = finger_joint: 0 open, {g['q_max']} closed (read from the STS3215 on the handle axle: q = 2 x its angle). -->
<robot name="scissor_umi_{kin.GRIPPER.replace('-', '')}">
  <link name="base_link"/>{''.join(jaw)}{frames_xml("base_link")}
</robot>
"""


def head_xacro():
    import head
    zf = head.flange_z() / 1000.0
    return f"""<?xml version="1.0"?>
<!-- The D405 on the team's UR camera plate (ur_camera_plate), on a Robotiq {kin.GRIPPER}: include after the gripper's
     own URDF/xacro. The plate puts the coupling {head.BOSS_TOP_M - head.FLANGE_M:.0f} mm further from the UR flange:
     add {(head.BOSS_TOP_M - head.FLANGE_M) / 1000:.3f} m to the flange -> coupling joint (the flange face is at
     z = {zf:.4f} m in robotiq_arg2f_base_link). The handheld's d405_optical_frame is at the same transform. -->
<robot xmlns:xacro="http://www.ros.org/wiki/xacro">
  <xacro:macro name="scissor_umi_camera" params="prefix:='' parent:=robotiq_arg2f_base_link">{frames_xml("${parent}", "${prefix}", quest=False)}
  </xacro:macro>
</robot>
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"scissor_umi_{kin.GRIPPER}.urdf").write_text(handheld())
    (OUT / f"{kin.GRIPPER}_camera.urdf.xacro").write_text(head_xacro())
    print("wrote", OUT)


if __name__ == "__main__":
    main()
